"""界面图标字形的**单一来源**（v9.18.0，需求 16）。

用户原话：
  「2.所有图标都简洁一点，要简洁、清晰」

## 为什么要收口到一个文件

以前图标是散落在 8 个文件里的几十个彩色 Emoji（U+1F4CA 数据表、U+1F465 团队、
U+1F9E0 大脑、U+1F50C 插头、U+23F0 闹钟 …）。问题有两条：

1. **看起来不简洁**。Emoji 在 Windows 上是**彩色位图**（Segoe UI Emoji），
   一屏里赤橙黄绿七八种颜色、还是实心大色块，跟这套扁平的浅灰界面完全不搭。
   用户要的「简洁、清晰」，落到可执行的标准就是：**单色、细线、几何形**。
2. **不能换、不好查**。想统一换一套图标，得在 8 个文件里逐个找；
   而且新加一个 Emoji 也没人拦着 —— 最后又回到五颜六色。

所以现在：所有图标字形都在这里的 `ICON` 表里，`app/` 下的 UI 文案一律 `ic("名字")`。

## ⚠ 选字形的铁律（血泪史）

`themes.qss()` 的字体族是
`"Microsoft YaHei", "SimHei", "Segoe UI", "Segoe UI Symbol", "Segoe UI Emoji"`。
**一旦 QSS 显式指定了 font-family，Qt 就只在这个列表里找字形，找不到就是空心方块。**

v9.13.1 之前列表里缺 `"Segoe UI Symbol"` / `"Segoe UI Emoji"`，
于是 ⚙(U+2699) / ⏹(U+23F9) 这类只存在于符号字体里的字符全画成豆腐块。
更坑的是：**单独一个 "⚙" 能回退成功，写成 "⚙ 执行代码" 就失败** ——
所以任何"只看单字符"的检查都是假的，必须在**真实混排形态**下验。

因此本表里每一个字形都满足：
- 落在 **Segoe UI Symbol / Microsoft YaHei** 覆盖区（几何图形 U+25xx、
  杂项符号 U+26xx、装饰符号 U+27xx、杂项符号与箭头 U+2Bxx、杂项技术符号 U+23xx）；
- **Emoji_Presentation=No** —— 也就是默认走**文字呈现**，渲染出来是单色的。
  （反例 —— 下面这些码位在 Windows 上是**彩色**的，一律不准进这张表：
   U+23F0 闹钟、U+23F1 秒表、U+23F3 沙漏、U+231B 沙漏、U+26A1 闪电、
   U+2B50 五角星、U+26D4 禁止、U+270D 写字手、U+2705 绿勾、U+274C 红叉、
   U+1F300–U+1FAFF 整段。"彩色"是可以用像素量化测的 ——
   见 `tests/probe_icons_v9180.py` 的 `colorful()`：数"饱和度较高的像素"，>3 就算彩色。）

`tests/probe_icons_v9180.py` 会把这张表 + 全部源码里出现过的符号字符
逐个按「图标 + 中文」的真实混排形态渲染一遍，检查：
① 不是空心方块；② 不会与"必定缺失字符"的方块撞脸；③ 渲染出来是单色（不是彩色的）。
**往这里加新图标之前，先跑那个探针。**
"""
