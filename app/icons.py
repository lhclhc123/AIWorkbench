# 兜底字形：查不到名字时用它，**绝不返回空串**（空串会让按钮塌掉）
FALLBACK = "\u00B7"


def ic(name, default=None):
    """取图标字形。查不到就返回 `default`，再没有就返回 FALLBACK。"""
    if default is not None:
        return ICON.get(name, default)
    return ICON.get(name, FALLBACK)


def render(name, text, sep=" "):
    """拼成「图标 + 空格 + 文字」。文字为空时只给图标。"""
    glyph = ic(name)
    return f"{glyph}{sep}{text}" if text else glyph
